"""Quét phụ thuộc máy cũ và chuỗi giống bí mật; không in nội dung khớp."""
from pathlib import Path
import argparse
import os
import re
import unicodedata
import importlib.util
_export_spec = importlib.util.spec_from_file_location("portable_export", Path(__file__).with_name("export_clean.py"))
_export = importlib.util.module_from_spec(_export_spec)
_export_spec.loader.exec_module(_export)
repository_files = _export.repository_files

def load_business_terms():
    """Danh sách riêng nằm ngoài repo; thiếu cấu hình không chặn phần quét khác."""
    configured = os.environ.get('AO_SENSITIVE_TERMS_FILE')
    if configured:
        try:
            terms = tuple(line.strip() for line in Path(configured).expanduser().read_text(
                encoding='utf-8-sig').splitlines() if line.strip())
            if terms:
                return terms
        except (OSError, UnicodeError):
            pass
    print('CẢNH BÁO: chưa cấu hình danh sách từ nhạy cảm — chưa quét tên kinh doanh')
    return ()

def fold_business(text):
    text = text.casefold().replace("đ", "d")
    return "".join(c for c in unicodedata.normalize("NFD", text) if unicodedata.category(c) != "Mn")

def business_tokens(line, terms):
    # Bỏ dấu và dấu phân cách để bắt cả tên ghép trong mã định danh.
    text = re.sub(r"[\W_]+", "", fold_business(line))
    return [term for term in terms
            if re.sub(r"[\W_]+", "", fold_business(term)) in text]

# Whitelist chính xác theo file/dòng; lý do được kiểm cùng điều kiện.
# Chỉ các biểu thức phát hiện/redact và fixture giả, không miễn cả thư mục.
def allowed(rel, line, kind, token=None):
    if rel == '.gitignore' and kind == 'key-dir':
        return line.strip() == '**/' + '.' + 'worker-keys/'  # Chặn secret directory khỏi git.
    if rel == 'tools/ao-memory/common.py' and kind == 'secret':
        return line.startswith('SECRET = re.compile(') and token == 'bearer\\s+'  # Biểu thức redact, không phải khóa.
    if rel == 'tools/ao-memory/tests/test_ao_memory.py' and kind == 'secret':
        return token == 's' + 'k-SECRET123'  # Fixture giả để thử redact.
    if rel == 'tools/ao-memory/tests/test_ao_run.py' and kind == 'secret':
        return token in ['nv' + 'api-FAKEKEY1234','s' + 'k-FAKEKEY1234','Bearer' + ' fakekey1234']  # Chỉ fixture giả.
    if rel == 'tools/ao-memory/tests/test_supervisor_io.py' and kind == 'secret':
        return token == 's' + 'k-example123'  # Fixture giả để thử che lỗi.
    return False

def scan(root):
    terms = load_business_terms()
    # Ghép token để scanner không tự khớp danh sách mẫu của nó.
    # Đường dẫn máy: thư mục home hiện tại + danh sách thêm trong AO_SCAN_MACHINE_PATHS (phân cách bằng os.pathsep).
    home = Path.home()
    literals = [str(home), home.as_posix(), '.'+'worker-keys'] + [p for p in os.environ.get('AO_SCAN_MACHINE_PATHS','').split(os.pathsep) if p]
    secret = re.compile(r'(?i)(?<![\w-])(?:nv' + r'api-[A-Za-z0-9_-]+|s' + r'k-[A-Za-z0-9_-]+|Bearer\s+[^\s\"\x27]+|api_key\s*=\s*[^\s,\"\x27]+)')
    findings=[]
    business_files = {p.as_posix() for p in repository_files(root)}
    for f in sorted(root.rglob('*')):
        if not f.is_file() or any(p in ('.git','__pycache__') for p in f.relative_to(root).parts): continue
        # Generated bytecode is not part of the portable source; all other files are checked.
        if f.suffix in ('.pyc','.pyo'): continue
        try: text=f.read_text(encoding='utf-8-sig')
        except UnicodeError:
            findings.append((str(f.relative_to(root)),0,'binary/unreadable')); continue
        rel=f.relative_to(root).as_posix()
        for n,line in enumerate(text.splitlines(),1):
            normalized=line.replace('\\\\','\\')
            kinds=set()
            if rel in business_files and business_tokens(line, terms): kinds.add('business-name')
            for needle in literals:
                if needle.casefold() in normalized.casefold(): kinds.add('key-dir' if needle.startswith('.') else 'machine-path')
            for match in secret.finditer(line):
                if not allowed(rel,line,'secret',match.group()): kinds.add('secret')
            for kind in sorted(kinds):
                if kind == 'secret' or not allowed(rel,line,kind):findings.append((rel,n,kind))
    return findings

def main():
    p=argparse.ArgumentParser(); p.add_argument('--root',type=Path,default=Path(os.environ.get('AO_ROOT') or Path(__file__).resolve().parents[2]))
    args=p.parse_args(); findings=scan(args.root.resolve())
    for file,line,kind in findings:print(f'{file}:{line}: {kind} (nội dung không được in)')
    print(f'SCAN_PATHS: {len(findings)} vi phạm')
    return 1 if findings else 0

if __name__=='__main__':raise SystemExit(main())
